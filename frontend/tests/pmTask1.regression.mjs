// PM 모드 Task1(pmTask1.js) 회귀 테스트.
// 로컬 GCP 자격증명 없이도 파싱 로직 + mock LLM 경로(PM 프롬프트 사용 여부)를 검증한다.
// 실행: node frontend/tests/pmTask1.regression.mjs
// 샘플 엑셀은 저장소 밖 로컬 경로를 참조하므로, 샘플 파일이 없는 환경에서는
// 해당 checkSample 블록만 건너뛰고 합성 테스트/mock 테스트는 항상 실행된다.
import * as XLSX from 'xlsx';
import fs from 'fs';
import path from 'path';
import { parsePmWorkbook, PM_ID_PREFIX, runPmTask1 } from '../src/pmTask1.js';

const SAMPLE_LARGE = '/Users/cyj/Desktop/요구사항정의서샘플.xlsx';
const SAMPLE_SMALL = '/Users/cyj/Desktop/보이스피싱/보이스피싱_요구사항정의서_v2.xlsx';

function loadWorkbook(p) {
    const buf = fs.readFileSync(p);
    return XLSX.read(buf, { type: 'buffer' });
}

function checkSample(name, filePath, expectations) {
    if (!fs.existsSync(filePath)) {
        console.log(`\n===== ${name} 건너뜀 (샘플 파일 없음: ${filePath}) =====`);
        return;
    }
    console.log(`\n===== ${name} (${path.basename(filePath)}) =====`);
    const wb = loadWorkbook(filePath);

    const results = parsePmWorkbook(wb);
    console.log('파싱된 요구사항 수:', results.length);

    const withBiz = results.filter(r => r.업무시스템).length;
    const withScope = results.filter(r => r.업무구분).length;
    const withDetail = results.filter(r => r.detail && r.detail !== '-').length;
    console.log('업무시스템 채움:', withBiz, '/', results.length);
    console.log('업무구분 채움:', withScope, '/', results.length);
    console.log('요구사항내용 채움:', withDetail, '/', results.length);

    const autoGenerated = results.filter(r => r.id.startsWith(`${PM_ID_PREFIX}-`));
    console.log('자동생성 ID 개수(원본에 ID 없는 행):', autoGenerated.length);
    const idPrefixes = [...new Set(results.map(r => r.id.split('-')[0]))];
    console.log('ID 접두사 종류:', idPrefixes);

    const typeDist = {};
    for (const r of results) typeDist[r.구분 || '(빈값)'] = (typeDist[r.구분 || '(빈값)'] || 0) + 1;
    console.log('기능/비기능 구분 분포:', typeDist);

    console.log('샘플 3건:');
    for (const r of results.slice(0, 3)) {
        console.log('  ', JSON.stringify({ id: r.id, title: r.title, 업무시스템: r.업무시스템, 업무구분: r.업무구분, 구분: r.구분 }));
    }

    if (expectations) expectations(results);
}

checkSample('샘플1(대규모 3단계층)', SAMPLE_LARGE, (results) => {
    const bad = results.filter(r => !r.id.startsWith('REQ-'));
    console.log('REQ- 로 시작하지 않는 ID 개수(예상 0):', bad.length, bad.map(r => r.id));
    const first = results[0];
    console.log('첫 항목 업무구분 경로:', first.업무구분, '(기대: "공통관리 > SDK > UI 공통")');
    if (first.업무구분 !== '공통관리 > SDK > UI 공통') throw new Error('업무구분 계층 병합 실패');
    if (first.id !== 'REQ-AA-001') throw new Error('원본 ID 불일치');
    if (first.업무시스템 !== 'Front SDK') throw new Error('업무시스템 파싱 실패');
});

checkSample('샘플2(소규모 단일컬럼+시트분리)', SAMPLE_SMALL, (results) => {
    const bad = results.filter(r => !r.id.startsWith('REQ-VP-'));
    console.log('REQ-VP- 로 시작하지 않는 ID 개수(예상 0):', bad.length, bad.map(r => r.id));
    const func = results.filter(r => r.구분 === '기능');
    const nonfunc = results.filter(r => r.구분 === '비기능');
    console.log('기능:', func.length, '비기능:', nonfunc.length, '(기대: 13 / 10)');
    if (func.length !== 13 || nonfunc.length !== 10) throw new Error('시트명 기반 기능/비기능 판별 실패');
    const first = results.find(r => r.id === 'REQ-VP-001');
    console.log('REQ-VP-001 업무구분(기대 "통화"):', first.업무구분);
    if (first.업무구분 !== '통화') throw new Error('단일컬럼 업무구분 파싱 실패');
    if (first.업무시스템 !== 'App') throw new Error('업무시스템 파싱 실패');
});

// 합성 테스트: ID 없는 행 자동생성(PMREQ-{n})
console.log('\n===== 합성 테스트: ID 없는 행 자동생성 =====');
const synthWs = XLSX.utils.aoa_to_sheet([
    ['요구사항ID', '업무시스템', '업무구분', '요구사항명', '요구사항내용'],
    ['REQ-X-001', 'SYS', '결제', '결제 기능', '결제를 처리한다'],
    [null, 'SYS', '결제', 'ID 없는 행', 'ID가 없는 요구사항도 통과해야 한다'],
]);
const synthWb = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(synthWb, synthWs, '기능요구사항');
const synthResults = parsePmWorkbook(synthWb);
console.log(synthResults.map(r => ({ id: r.id, title: r.title, 구분: r.구분 })));
if (synthResults[0].id !== 'REQ-X-001') throw new Error('원본 ID 유지 실패');
if (!synthResults[1].id.startsWith(`${PM_ID_PREFIX}-`)) throw new Error('PMREQ 자동생성 실패');
if (synthResults[1].구분 !== '기능') throw new Error('시트명 기반(기능요구사항) 구분 판별 실패');
console.log('자동생성 ID:', synthResults[1].id, '(PMREQ-{n} 형식 확인)');

// runPmTask1 흐름 검증 (LLM 호출부는 mock으로 대체 — 실제 GCP 자격증명 없이도 로직 검증 가능)
console.log('\n===== runPmTask1 로직(청크/병합) mock 테스트 =====');
const mockCallBackendAPI = async (promptData, systemInstruction, schemaDefinition) => {
    if (!systemInstruction.includes('PM(프로젝트 관리자)')) throw new Error('PM 프롬프트가 전달되지 않음');
    if (systemInstruction.includes('UIUX 기획자')) throw new Error('UIUX 프롬프트가 섞여 들어옴');
    return { requirements: [{ id: 'TXT-001', title: 'mock', detail: 'mock detail', 구분: '기능', 우선순위: '상', 업무시스템: '', 업무구분: '', ambiguity_hitl: { is_ambiguous: false, original_text: 'mock', corrected_text: '', ambiguity_reason: '' } }] };
};
const textResult = await runPmTask1({ combinedText: '텍스트 기반 요구사항 샘플', callBackendAPI: mockCallBackendAPI });
console.log('텍스트 경로 결과:', textResult.requirements.length, '건');
if (textResult.requirements.length !== 1) throw new Error('텍스트 경로 실패');

console.log('\n모든 검증 통과');
